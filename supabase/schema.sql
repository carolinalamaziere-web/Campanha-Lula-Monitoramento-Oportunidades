create table if not exists public.eventos_conteudo (
  id bigint generated by default as identity primary key,
  conteudo_id text not null,
  tipo text not null check (tipo in ('clique', 'download', 'play')),
  plataforma text,
  formato text,
  url_destino text,
  origem text not null default 'painel',
  criado_em timestamptz not null default now()
);

create index if not exists eventos_conteudo_consulta_idx
  on public.eventos_conteudo (conteudo_id, tipo, criado_em desc);

create table if not exists public.config (
  chave text primary key,
  valor jsonb not null default '{}'::jsonb,
  atualizado_em timestamptz not null default now()
);

create or replace view public.top20_por_plataforma_formato as
select *
from (
  select
    t.*,
    row_number() over (
      partition by t.plataforma, t.formato
      order by t.interacoes desc, t.publicado_em desc nulls last
    ) as posicao_filtro
  from public.trending_top20 t
) ranqueado
where posicao_filtro <= 20;

